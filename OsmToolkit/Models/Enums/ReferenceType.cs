namespace OsmToolkit
{
    /// <summary>
    /// Contains <see cref="OsmEntity"/> reference types.
    /// </summary>
    public enum ReferenceType
    {
        /// <summary>
        /// Represents members of class type <see cref="Node"/>.
        /// </summary>
        node,

        /// <summary>
        /// Represents members of class type <see cref="Way"/>.
        /// </summary>
        way,

        /// <summary>
        /// Represents members of class type <see cref="Relation"/>.
        /// </summary>
        relation
    }
}
